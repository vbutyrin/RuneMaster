private fun expandSynonyms(text: String): String {
    val normalized = normalizeText(text)
    val additions = mutableListOf<String>()

    synonymGroups.forEach { (canonical, words) ->
        if (words.any { normalized.contains(normalizeText(it)) }) {
            additions += canonical
            additions += words
        }
    }

    return normalized + " " + additions.joinToString(" ")
}

private val negations = listOf(
    "не хочу",
    "не нужно",
    "не надо",
    "не желаю",
    "не собираюсь"
)

private fun containsNegatedGoal(text: String, phrase: String): Boolean {
    val t = normalizeText(text)
    val p = normalizeText(phrase)

    return negations.any { neg ->
        val pos = t.indexOf(neg)
        val target = t.indexOf(p)
        pos >= 0 && target >= pos && target - pos < 45
    }
}

private fun contextBoost(
    text: String,
    concept: ProblemConcept
): Int {
    val t = expandSynonyms(text)

    var score = 0

    when (concept.domain) {
        "Финансы" ->
            if (listOf("деньг","финанс","зарплат","долг","кредит","прибыл","money")
                    .any { t.contains(it) }) score += 18

        "Работа", "Карьера" ->
            if (listOf("работ","началь","ваканс","карьер","должност","job")
                    .any { t.contains(it) }) score += 18

        "Семья" ->
            if (listOf("сем","дом","муж","жен","family")
                    .any { t.contains(it) }) score += 18

        "Отношения" ->
            if (listOf("отнош","люб","партнер","партнёр","жених","сужен","partner")
                    .any { t.contains(it) }) score += 18
    }

    if (concept.id.contains("conflict") &&
        listOf("ссор","конфликт","руга","скандал","задолб","достал","сжира","conflict")
            .any { t.contains(it) }
    ) score += 22

    return score
}


private fun normalizeText(value: String): String {
    return value
        .lowercase()
        .replace('ё', 'е')
        .replace(Regex("[^а-яa-z0-9\\s-]"), " ")
        .replace(Regex("\\s+"), " ")
        .trim()
}

private fun stemRu(word: String): String {
    val w = normalizeText(word)
    val endings = listOf(
        "иями","ями","ами","его","ого","ему","ому","ыми","ими",
        "ией","ей","ой","ий","ый","ая","яя","ое","ее","ам","ям",
        "ах","ях","ом","ем","ов","ев","ую","юю","а","я","ы","и",
        "у","ю","е","о"
    )
    for (e in endings) {
        if (w.length > e.length + 3 && w.endsWith(e)) {
            return w.dropLast(e.length)
        }
    }
    return w
}

private fun phraseScore(text: String, phrase: String): Int {
    val t = normalizeText(text)
    val p = normalizeText(phrase)

    if (t.contains(p)) return 100

    val textWords = t.split(" ").filter { it.length > 2 }.map(::stemRu).toSet()
    val phraseWords = p.split(" ").filter { it.length > 2 }.map(::stemRu)

    if (phraseWords.isEmpty()) return 0

    val hits = phraseWords.count { pw ->
        textWords.any { tw ->
            tw == pw || (tw.length >= 5 && pw.length >= 5 &&
                (tw.startsWith(pw.take(5)) || pw.startsWith(tw.take(5))))
        }
    }

    return ((hits.toFloat() / phraseWords.size) * 80).toInt()
}

private fun analyzeRequest(text: String): AnalysisResult {
    val normalized = normalizeText(text)
    val expanded = expandSynonyms(text)

    val detected = problemDictionary.mapNotNull { concept ->
        val scored = concept.phrases
            .map { phrase ->
                var score = phraseScore(expanded, phrase)

                score += contextBoost(text, concept)

                if (containsNegatedGoal(normalized, phrase)) {
                    score -= 55
                }

                phrase to score.coerceIn(0, 100)
            }
            .filter { it.second >= 55 }
            .sortedByDescending { it.second }

        if (scored.isEmpty()) null
        else DetectedProblem(
            concept = concept,
            confidence = scored.first().second,
            matchedWords = scored.take(4).map { it.first }
        )
    }
    .distinctBy { it.concept.id }
    .sortedWith(
        compareByDescending<DetectedProblem> { it.confidence }
            .thenBy { it.concept.domain }
    )

    return AnalysisResult(text, detected)
}

private fun recommendedRunes(result: AnalysisResult): List<Pair<RuneInfo, Int>> {
    val scores = mutableMapOf<String, Int>()

    result.problems.forEachIndexed { index, detected ->
        detected.concept.runeNames.forEachIndexed { runeIndex, runeName ->
            val weight = when (runeIndex) {
                0 -> 6
                1 -> 4
                2 -> 3
                else -> 2
            }
            scores[runeName] = (scores[runeName] ?: 0) + weight +
                    if (index == 0) 2 else 0
        }
    }

    return scores.entries
        .sortedByDescending { it.value }
        .mapNotNull { e ->
            runes.find { it.name == e.key }?.let { it to e.value }
        }
        .take(7)
}


