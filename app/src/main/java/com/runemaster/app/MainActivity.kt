@Composable
private fun JournalScreen(
    onBack: () -> Unit
) {
    val context =
        androidx.compose.ui.platform.LocalContext.current

    var entries by remember {
        mutableStateOf(LocalStore.loadJournal(context))
    }

    var client by remember {
        mutableStateOf("")
    }

    var request by remember {
        mutableStateOf("")
    }

    var notes by remember {
        mutableStateOf("")
    }

    LazyColumn(
        modifier = Modifier
            .fillMaxSize()
            .background(Bg)
            .padding(horizontal = 18.dp),
        contentPadding = PaddingValues(bottom = 50.dp)
    ) {
        item {
            TextButton(onClick = onBack) {
                Text("‹ ГЛАВНАЯ", color = Gold)
            }

            AppHeader(
                "ЖУРНАЛ",
                "Локальные рабочие записи"
            )

            Spacer(Modifier.height(16.dp))

            Card(
                colors = CardDefaults.cardColors(
                    containerColor = Color(0xFF131B17)
                )
            ) {
                Text(
                    "Записи хранятся только в локальном хранилище приложения. Для рабочих заметок предпочтительнее использовать псевдоним или номер клиента вместо лишних персональных данных.",
                    color = Text,
                    modifier = Modifier.padding(15.dp),
                    fontSize = 12.sp,
                    lineHeight = 18.sp
                )
            }

            Spacer(Modifier.height(15.dp))

            OutlinedTextField(
                value = client,
                onValueChange = { client = it },
                modifier = Modifier.fillMaxWidth(),
                label = {
                    Text("Клиент / псевдоним")
                },
                singleLine = true
            )

            Spacer(Modifier.height(8.dp))

            OutlinedTextField(
                value = request,
                onValueChange = { request = it },
                modifier = Modifier.fillMaxWidth(),
                label = {
                    Text("Запрос")
                },
                minLines = 2
            )

            Spacer(Modifier.height(8.dp))

            OutlinedTextField(
                value = notes,
                onValueChange = { notes = it },
                modifier = Modifier.fillMaxWidth(),
                label = {
                    Text("Результат / заметки")
                },
                minLines = 3
            )

            Spacer(Modifier.height(10.dp))

            Button(
                onClick = {
                    if (request.isNotBlank()) {
                        val newEntry = JournalEntry(
                            id = System.currentTimeMillis(),
                            client =
                                client.ifBlank {
                                    "Без имени"
                                },
                            request = request.trim(),
                            result = notes.trim(),
                            date = currentDateString()
                        )

                        entries =
                            listOf(newEntry) + entries

                        LocalStore.saveJournal(
                            context,
                            entries
                        )

                        client = ""
                        request = ""
                        notes = ""
                    }
                },
                modifier = Modifier.fillMaxWidth(),
                colors = ButtonDefaults.buttonColors(
                    containerColor = Gold,
                    contentColor = Color.Black
                )
            ) {
                Text(
                    "СОХРАНИТЬ ЗАПИСЬ",
                    fontWeight = FontWeight.Bold
                )
            }

            Spacer(Modifier.height(25.dp))

            Text(
                "СОХРАНЁННЫЕ ЗАПИСИ",
                color = Gold,
                fontSize = 12.sp,
                fontWeight = FontWeight.Bold
            )

            if (entries.isEmpty()) {
                Text(
                    "Журнал пока пуст.",
                    color = Muted,
                    modifier = Modifier.padding(top = 12.dp)
                )
            }

            entries.forEach { entry ->
                var expanded by remember(entry.id) {
                    mutableStateOf(false)
                }

                Card(
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(vertical = 5.dp)
                        .clickable {
                            expanded = !expanded
                        },
                    colors = CardDefaults.cardColors(
                        containerColor = CardBg
                    )
                ) {
                    Column(
                        Modifier.padding(16.dp)
                    ) {
                        Text(
                            entry.client,
                            color = GoldLight,
                            fontWeight = FontWeight.Bold
                        )

                        Text(
                            entry.date,
                            color = Muted,
                            fontSize = 11.sp
                        )

                        Spacer(Modifier.height(5.dp))

                        Text(
                            entry.request,
                            color = Text,
                            fontSize = 13.sp,
                            lineHeight = 18.sp
                        )

                        AnimatedVisibility(expanded) {
                            Column {
                                if (entry.result.isNotBlank()) {
                                    Spacer(Modifier.height(10.dp))

                                    Text(
                                        "ЗАМЕТКИ",
                                        color = Gold,
                                        fontSize = 10.sp
                                    )

                                    Text(
                                        entry.result,
                                        color = Text,
                                        fontSize = 13.sp,
                                        lineHeight = 18.sp
                                    )
                                }

                                Spacer(Modifier.height(12.dp))

                                Button(
                                    onClick = {
                                        entries =
                                            entries.filterNot {
                                                it.id == entry.id
                                            }

                                        LocalStore.saveJournal(
                                            context,
                                            entries
                                        )
                                    },
                                    colors =
                                        ButtonDefaults.buttonColors(
                                            containerColor =
                                                Color(0xFF382020),
                                            contentColor =
                                                Color(0xFFFFC8C8)
                                        )
                                ) {
                                    Text("УДАЛИТЬ")
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}

