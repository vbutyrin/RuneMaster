            .background(Bg)
    ) {
        RuneAmbientBackground()
        content()
    }
}

@Composable
fun RuneMasterApp() {
    val professionalViewModel:
        ProfessionalViewModel = viewModel()

    var screen by remember {
        mutableStateOf<Screen>(Screen.Home)
    }

    var lastQuery by remember {
        mutableStateOf("")
    }

    /*
     * Единая точка сохранения сеанса клиента:
     * используется и редактором (композиция рун),
     * и быстрым сохранением без редактирования.
     */
    fun saveClientSession(
        draft: ClientSessionDraft,
        compositionJson: String,
        formulaExplanation: String
    ) {
        val analysis =
            RuneSolutionEngine
                .solve(draft.problem)

        val analysisText =
            buildString {
                append("Сферы: ")
                append(
                    analysis.analysis
                        .domains
                        .joinToString()
                )

                append("\nПроблемы: ")
                append(
                    analysis.analysis
                        .problems
                        .joinToString()
                )

                append("\nЦели: ")
                append(
                    analysis.analysis
                        .intents
                        .joinToString()
                )
            }

        professionalViewModel
            .saveCompleteSession(
                clientName =
                    draft.clientName,
                clientNotes =
                    draft.clientNotes,
                request =
                    draft.problem,
                analysis =
                    analysisText,
                practitionerNotes =
                    draft.practitionerNotes,
                formulaTitle =
                    draft.formula.title,
                intention =
                    draft.formula.intention,
                primaryRune =
                    draft.formula.primaryRune,
                supportingRunes =
                    draft.formula.supportingRunes,
                formulaExplanation =
                    formulaExplanation,
                compositionJson =
                    compositionJson,
                onSaved = {
                    screen =
                        Screen.Journal
                }
            )
    }

    BackHandler(screen !is Screen.Home) {
        screen = Screen.Home
    }

    when (val current = screen) {
        Screen.Home -> HomeScreen(
            navigate = {
                screen = it
            },
            savedQuery = lastQuery,
            onQueryChange = {
                lastQuery = it
            }
        )
        Screen.Runes -> RuneListScreen(
            onBack = { screen = Screen.Home },
            onRune = {
                screen = Screen.RuneDetail(
                    rune = it,
                    returnTo = Screen.Runes
                )
            }
        )
        is Screen.RuneDetail -> RuneDetailScreen(
            current.rune,
            onBack = {
                screen = current.returnTo
            }
        )
        is Screen.Analysis -> SemanticAnalysisScreen(
            text = current.text,
            runeLookup = { runeName ->
                runes.find { rune ->
                    rune.name == runeName
                }
            },
            onBack = {
                screen = Screen.Home
            },
            onRune = { rune: RuneInfo ->
                screen = Screen.RuneDetail(
                    rune = rune,
                    returnTo = current
                )
            },
            onOpenFormula = { formula ->
                screen = Screen.FormulaEditor(formula)
            }
        )
        Screen.Diagnostics -> DiagnosticsScreen(
            onBack = { screen = Screen.Home },
            onRune = { screen = Screen.RuneDetail(it) }
        )
        Screen.Formulas -> FormulasScreen(
            onBack = { screen = Screen.Home }
        )
        Screen.Constructor -> RuneEditorScreen(
            onBack = { screen = Screen.Home }
        )
        is Screen.FormulaEditor -> RuneEditorScreen(
            onBack = {
                screen =
                    current.clientDraft?.let {
                        Screen.ClientSession(it)
                    } ?: Screen.Home
            },
            initialFormula = current.formula,
            clientDraft = current.clientDraft,
            onSaveClient = { draft, editorRunes ->
                saveClientSession(
                    draft = draft,
                    compositionJson =
                        serializeEditorRunes(
                            editorRunes
                        ),
                    formulaExplanation =
                        "Индивидуальная формула, отредактированная в Rune Editor"
                )
            }
        )

        Screen.Candles -> CandlesScreen(
            onBack = { screen = Screen.Home }
        )
        Screen.Sources -> SourcesScreen(
            onBack = { screen = Screen.Home }
        )
        is Screen.ClientSession -> NewClientSessionScreen(
            initial = current.draft,
            runeLookup = { runeName ->
                runes.find { rune ->
                    rune.name == runeName
                }
            },
            onBack = {
                screen = Screen.Journal
            },
            onRune = { rune, draft ->
                if (draft != null) {
                    screen = Screen.ClientRuneDetail(
                        rune = rune,
                        draft = draft
                    )
                }
            },
            onFormula = { draft ->
                screen = Screen.FormulaEditor(
                    formula = draft.formula,
                    clientDraft = draft
                )
            },
            onQuickSave = { draft ->
                saveClientSession(
                    draft = draft,
                    compositionJson = "",
                    formulaExplanation =
                        "Формула сохранена без редактирования в Rune Editor"
                )
            }
        )

        is Screen.ClientRuneDetail -> RuneDetailScreen(
            rune = current.rune,
            onBack = {
                screen = Screen.ClientSession(
                    draft = current.draft
                )
            }
        )

        Screen.Journal -> ProfessionalWorkspaceScreen(
            onBack = {
                screen = Screen.Home
            },
            onNewClientSession = {
                screen = Screen.ClientSession()
            }
        )
        Screen.Favorites -> FavoritesScreen(
            onBack = { screen = Screen.Home },
            onRune = { screen = Screen.RuneDetail(it) }
        )
        is Screen.Placeholder -> PlaceholderScreen(
            current.title,
            current.description,
            onBack = { screen = Screen.Home }
        )
    }
