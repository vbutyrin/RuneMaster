@Composable
private fun RuneAmbientBackground() {
    val transition = rememberInfiniteTransition(label = "runeBackground")

    val phase by transition.animateFloat(
        initialValue = 0f,
        targetValue = 24f,
        animationSpec = infiniteRepeatable(
            animation = tween(
                durationMillis = 120000,
                easing = LinearEasing
            ),
            repeatMode = RepeatMode.Restart
        ),
        label = "runePhase"
    )

    val index = phase.toInt().coerceIn(0, 23)
    val local = phase - phase.toInt()
    val alpha = (sin(local * Math.PI).toFloat() * 0.12f)
        .coerceIn(0f, 0.12f)

    val symbol = runes.getOrNull(index)?.symbol ?: "ᚠ"

    Canvas(
        modifier = Modifier.fillMaxSize()
    ) {
        drawContext.canvas.nativeCanvas.drawText(
            symbol,
            size.width * 0.50f,
            size.height * 0.60f,
            Paint().apply {
                color = android.graphics.Color.rgb(214, 169, 76)
                textSize = size.minDimension * 0.62f
                textAlign = Paint.Align.CENTER
                this.alpha = (alpha * 255).toInt()
                isAntiAlias = true
            }
        )

        val t = local * 6.28318f

        repeat(16) { i ->
            val x = size.width *
                (0.10f + ((i * 0.057f + local * 0.17f) % 0.80f))
            val y = size.height *
                (0.15f + ((i * 0.113f + local * 0.11f) % 0.70f))

            val pulse = (0.25f +
                0.20f * sin(t + i).toFloat())
                .coerceIn(0.05f, 0.45f)

            drawCircle(
                color = Gold.copy(alpha = pulse),
                radius = 1.2f + (i % 3),
                center = Offset(x, y)
            )
        }
    }
}

